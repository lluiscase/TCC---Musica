from pathlib import Path

from flask import Blueprint, current_app, request, send_file, send_from_directory

from backend.extensions import db
from backend.feedback import completed_count, current_model, execution_feedback
from backend.models import Analysis, Execution, Reference
from backend.references import create_reference, reference_detail
from backend.worker import notify
from processamento.feedback import ERROR_TYPES, model_summary

bp = Blueprint("api", __name__, url_prefix="/api")


def _error(message, status=400):
    return {"error": message}, status


@bp.post("/execute-analyse")
def execute_analyse():
    """formData: audio (one .wav per execution), executions, referenceId, startSecond?, endSecond?"""
    files = request.files.getlist("audio")
    executions = request.form.get("executions", type=int)
    reference_id = request.form.get("referenceId", type=int)
    start_second = request.form.get("startSecond", type=float)
    end_second = request.form.get("endSecond", type=float)

    if not executions or executions < 1:
        return _error("'executions' deve ser um número maior que zero")
    if len(files) != executions:
        return _error(f"Esperados {executions} áudios, recebidos {len(files)}")
    if any(not file.filename.lower().endswith(".wav") for file in files):
        return _error("Todos os áudios devem ser .wav")
    if start_second is not None and end_second is not None and end_second <= start_second:
        return _error("'endSecond' deve ser maior que 'startSecond'")

    if reference_id is None:
        reference = db.session.scalar(db.select(Reference).where(Reference.is_default))
    else:
        reference = db.session.get(Reference, reference_id)
    if reference is None:
        return _error("Referência não encontrada", 404)

    analysis = Analysis(
        reference=reference,
        total_executions=executions,
        start_second=start_second,
        end_second=end_second,
    )
    db.session.add(analysis)
    db.session.flush()

    upload_dir = Path(current_app.config["UPLOAD_DIR"]) / str(analysis.id)
    upload_dir.mkdir(parents=True, exist_ok=True)

    for number, file in enumerate(files, start=1):
        path = upload_dir / f"execucao{number}.wav"
        file.save(path)
        analysis.executions.append(Execution(number=number, audio_path=str(path)))

    db.session.commit()

    notify()

    return {"content": {"analysisId": analysis.id, "status": analysis.status}}, 202


@bp.get("/analyses")
def list_analyses():
    """Rows of the analyses table, newest first. ?referenceId= only the analyses of that reference"""
    query = db.select(Analysis).order_by(Analysis.id.desc())
    reference_id = request.args.get("referenceId", type=int)
    if reference_id is not None:
        query = query.where(Analysis.reference_id == reference_id)
    analyses = db.session.scalars(query).all()
    return {"content": [analysis.summary() for analysis in analyses]}


@bp.get("/result-analyse/<int:analysis_id>")
def result_analyse(analysis_id):
    analysis = db.session.get(Analysis, analysis_id)
    if analysis is None:
        return _error("Análise não encontrada", 404)

    content = analysis.to_dict()
    model = current_model()
    for execution, row in zip(analysis.executions, content["executions"]):
        try:
            row["feedback"] = execution_feedback(execution, model)
        except Exception:
            current_app.logger.exception("Erro ao gerar o feedback da execução %s", execution.id)
            row["feedback"] = None
    return {"content": content}


@bp.get("/files/<int:analysis_id>/<path:name>")
def result_file(analysis_id, name):
    """Files generated by the worker, e.g. the audio of the execution with clicks on each onset"""
    return send_from_directory(Path(current_app.config["RESULTS_DIR"]) / str(analysis_id), name)


@bp.get("/model")
def model_status():
    """Model trained by the worker with the executions of every user"""
    return {
        "content": {
            "errorTypes": [{"type": key, "label": value["label"]} for key, value in ERROR_TYPES.items()],
            "completedExecutions": completed_count(),
            "model": model_summary(current_model()),
        }
    }


@bp.get("/references")
def list_references():
    """Default reference first, then the ones created by the user, oldest first"""
    references = db.session.scalars(
        db.select(Reference).order_by(Reference.is_default.desc(), Reference.id)
    ).all()
    return {"content": [reference.summary() for reference in references]}


@bp.post("/references")
def new_reference():
    """formData: audio (.wav recorded or sent by the user), name"""
    file = request.files.get("audio")
    name = (request.form.get("name") or "").strip()

    if file is None:
        return _error("Envie o áudio da referência")
    if not file.filename.lower().endswith(".wav"):
        return _error("A referência deve ser um .wav")
    if not name:
        return _error("Dê um nome para a referência")

    try:
        reference = create_reference(file, name[:120])
    except Exception as error:
        current_app.logger.exception("Erro ao processar a referência")
        return _error(f"Não foi possível processar o áudio: {error}", 422)

    return {"content": reference_detail(reference)}, 201


def _get_reference(reference_id):
    reference = db.session.get(Reference, reference_id)
    if reference is None:
        return None, _error("Referência não encontrada", 404)
    return reference, None


@bp.get("/references/<int:reference_id>")
def reference(reference_id):
    reference, error = _get_reference(reference_id)
    return error or {"content": reference_detail(reference)}


@bp.get("/references/<int:reference_id>/audio")
def reference_audio(reference_id):
    reference, error = _get_reference(reference_id)
    return error or send_file(reference.audio_path, mimetype="audio/wav")
